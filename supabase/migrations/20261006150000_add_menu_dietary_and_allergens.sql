-- ============================================================
-- 1. CATÁLOGO DE CARACTERÍSTICAS DIETÉTICAS
-- ============================================================

CREATE TABLE public.dietary_attributes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  code text NOT NULL UNIQUE,

  name text NOT NULL,

  description text,

  display_order integer NOT NULL DEFAULT 0,

  is_active boolean NOT NULL DEFAULT true,

  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT dietary_attributes_code_not_empty
    CHECK (length(trim(code)) > 0),

  CONSTRAINT dietary_attributes_name_not_empty
    CHECK (length(trim(name)) > 0),

  CONSTRAINT dietary_attributes_display_order_non_negative
    CHECK (display_order >= 0)
);


-- ============================================================
-- 2. CATÁLOGO DOS 14 ALERGÉNIOS
-- ============================================================

CREATE TABLE public.allergens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  code text NOT NULL UNIQUE,

  name text NOT NULL,

  description text,

  display_order integer NOT NULL DEFAULT 0,

  is_active boolean NOT NULL DEFAULT true,

  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT allergens_code_not_empty
    CHECK (length(trim(code)) > 0),

  CONSTRAINT allergens_name_not_empty
    CHECK (length(trim(name)) > 0),

  CONSTRAINT allergens_display_order_non_negative
    CHECK (display_order >= 0)
);


-- ============================================================
-- 3. RELAÇÃO MENU ITEM ↔ DIETARY ATTRIBUTES
-- ============================================================

CREATE TABLE public.menu_item_dietary_attributes (
  menu_item_id bigint NOT NULL,

  dietary_attribute_id bigint NOT NULL,

  created_at timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (
    menu_item_id,
    dietary_attribute_id
  ),

  CONSTRAINT menu_item_dietary_attributes_menu_item_fkey
    FOREIGN KEY (menu_item_id)
    REFERENCES public.menu_items(id)
    ON DELETE CASCADE,

  CONSTRAINT menu_item_dietary_attributes_attribute_fkey
    FOREIGN KEY (dietary_attribute_id)
    REFERENCES public.dietary_attributes(id)
    ON DELETE RESTRICT
);


-- ============================================================
-- 4. RELAÇÃO MENU ITEM ↔ ALERGÉNIOS
-- ============================================================

CREATE TABLE public.menu_item_allergens (
  menu_item_id bigint NOT NULL,

  allergen_id bigint NOT NULL,

  created_at timestamptz NOT NULL DEFAULT now(),

  PRIMARY KEY (
    menu_item_id,
    allergen_id
  ),

  CONSTRAINT menu_item_allergens_menu_item_fkey
    FOREIGN KEY (menu_item_id)
    REFERENCES public.menu_items(id)
    ON DELETE CASCADE,

  CONSTRAINT menu_item_allergens_allergen_fkey
    FOREIGN KEY (allergen_id)
    REFERENCES public.allergens(id)
    ON DELETE RESTRICT
);


-- ============================================================
-- 5. ÍNDICES
-- ============================================================

CREATE INDEX menu_item_dietary_attributes_attribute_id_idx
  ON public.menu_item_dietary_attributes (
    dietary_attribute_id
  );

CREATE INDEX menu_item_allergens_allergen_id_idx
  ON public.menu_item_allergens (
    allergen_id
  );


