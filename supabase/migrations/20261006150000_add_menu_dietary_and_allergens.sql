-- ============================================================
-- 13. MANAGER — INSERIR CARACTERÍSTICAS
-- ============================================================

CREATE POLICY "menu_item_dietary_attributes_insert_manager"
ON public.menu_item_dietary_attributes
FOR INSERT
TO authenticated
WITH CHECK (
  is_current_user_restaurant_manager()
  AND EXISTS (
    SELECT 1
    FROM public.menu_items mi
    JOIN public.employees e
      ON e.restaurant_id = mi.restaurant_id
    JOIN public.roles r
      ON r.id = e.role_id
    WHERE mi.id = menu_item_dietary_attributes.menu_item_id
      AND e.user_id = auth.uid()
      AND e.status = 'active'
      AND r.name = 'manager'
  )
  AND EXISTS (
    SELECT 1
    FROM public.dietary_attributes da
    WHERE da.id = menu_item_dietary_attributes.dietary_attribute_id
      AND da.is_active = true
  )
);

CREATE POLICY "menu_item_allergens_insert_manager"
ON public.menu_item_allergens
FOR INSERT
TO authenticated
WITH CHECK (
  is_current_user_restaurant_manager()
  AND EXISTS (
    SELECT 1
    FROM public.menu_items mi
    JOIN public.employees e
      ON e.restaurant_id = mi.restaurant_id
    JOIN public.roles r
      ON r.id = e.role_id
    WHERE mi.id = menu_item_allergens.menu_item_id
      AND e.user_id = auth.uid()
      AND e.status = 'active'
      AND r.name = 'manager'
  )
  AND EXISTS (
    SELECT 1
    FROM public.allergens a
    WHERE a.id = menu_item_allergens.allergen_id
      AND a.is_active = true
  )
);


